from docx import Document
from docx.shared import Cm, Pt
from docx.enum.table import WD_TABLE_ALIGNMENT
from styles import (
    apply_gost_page_setup, add_gost_paragraph, add_gost_heading,
    set_academic_table_borders, format_cell
)

def build_tech_appendix_document(output_path: str):
    doc = Document()
    apply_gost_page_setup(doc)

    # Title
    add_gost_heading(doc, "ТЕХНИЧЕСКОЕ ПРИЛОЖЕНИЕ К ПРОЕКТУ RISKTWIN", space_before=0, space_after=4)
    add_gost_paragraph(
        doc,
        "Методология моделирования, математический аппарат, результаты экспериментальной валидации "
        "и дорожная карта технологической готовности (TRL). Автор: Сулейменов Ж.С. (КарТУ им. Сагинова).",
        space_after=8
    )

    # 1. Архитектура
    add_gost_heading(doc, "1. Архитектурная парадигма: Dual-Tower Neuro-Symbolic AI", space_before=6, space_after=4)
    add_gost_paragraph(
        doc,
        "В основу платформы RiskTwin заложена гибридная архитектура Neuro-Symbolic AI. В отличие от стандартных "
        "моделей градиентного бустинга, оперирующих исключительно ретроспективными финансовыми выписками, "
        "RiskTwin разделяет входящий поток признаков на две параллельные башни репрезентации (Dual-Tower):\n"
        "• Финансовая башня (Tower F): аккумулирует 7 фундаментальных макро- и транзакционных индикаторов (динамика остатка 7d/30d, "
        "коэффициент долговой нагрузки DSTI, частота обращений за кредитами, объем кредитных лимитов);\n"
        "• Психометрическая башня (Tower P): обрабатывает 9 поведенческих маркеров пассивного считывания "
        "(ночные входы в ДБО с 03:00 до 05:00, аномальное зависание на экране графика платежей свыше 90 секунд, спад трат "
        "на категорию «уход за собой и спорт», появление микрозаймов в МФО, покупки в ночных аптеках).",
        space_after=6
    )

    # 2. Математический аппарат
    add_gost_heading(doc, "2. Математический аппарат и алгоритмы оптимизации", space_before=6, space_after=4)
    add_gost_paragraph(
        doc,
        "2.1. Механизм кросс-внимания (Cross-Attention Fusion):\n"
        "Скрытые взаимосвязи между финансовым дефицитом и эмоциональным стрессом вычисляются через масштабированное "
        "произведение проекций:\n"
        "    Z = Softmax((Q_f · K_p^T) / sqrt(d_k)) · V_p\n"
        "где Q_f — векторное представление финансового состояния, K_p и V_p — проекции поведенческого стресса, "
        "d_k = 64 — размерность скрытого пространства.\n\n"
        "2.2. Асимметричная функция потерь (Cost-Sensitive Loss):\n"
        "Пропуск дефолта (False Negative) обходится банку в десятки раз дороже ложного срабатывания (False Positive), "
        "в связи с чем оптимизация проводится по взвешенной функции потерь:\n"
        "    L_cost = - [ c_1 · y · log(y_hat) + c_0 · (1 - y) · log(1 - y_hat) ]\n"
        "где c_1 = 5.0 (штрафной коэффициент пропуска дефолта), c_0 = 1.0.\n\n"
        "2.3. Модель выживаемости срока кассового разрыва (Survival Runway Model):\n"
        "Оценка времени до наступления неплатежеспособности T_runway моделируется пропорциональной функцией риска Кокса:\n"
        "    h(t | X) = h_0(t) · exp(W^T · Z)\n"
        "Математическое ожидание дней до исчерпания ликвидности определяется интегралом от функции выживания:\n"
        "    E[T] = ∫ S(t | X) dt",
        space_after=6
    )

    # 3. Экспериментальные данные и метрики
    add_gost_heading(doc, "3. Экспериментальная база, датасеты и метрики валидации", space_before=6, space_after=4)
    add_gost_paragraph(
        doc,
        "Калибровка и тестирование моделей проводились на базе открытого отраслевого датасета Home Credit Default Risk "
        "(307 511 заемщиков, 122 финансовых показателя) и синтетического генератора стресс-сценариев (10 000 временных "
        "рядов поведения клиентов при шоках потери дохода, роста расходов и снижения ликвидности).",
        space_after=4
    )

    tbl_met = doc.add_table(rows=5, cols=3)
    tbl_met.alignment = WD_TABLE_ALIGNMENT.CENTER
    tbl_met.autofit = False
    set_academic_table_borders(tbl_met)
    w_m = [Cm(6.0), Cm(5.5), Cm(5.5)]
    for row in tbl_met.rows:
        for j, w in enumerate(w_m):
            row.cells[j].width = w

    metrics_data = [
        ("Показатель эффективности", "Традиционный скоринг (Baseline)", "RiskTwin Neuro-Symbolic"),
        ("Качество ранней классификации (AUC-ROC)", "0.742", "0.887 (+14.5%)"),
        ("F1-Score на классе раннего стресса", "0.581", "0.824 (+24.3%)"),
        ("Точность прогноза срока до дефолта (MAE)", "±18.4 дней", "±4.2 дня (в 4.3 раза точнее)"),
        ("Горизонт упреждающего оповещения", "Day 1+ DPD (постфактум)", "Day -30 (за месяц до просрочки)")
    ]

    for i, row in enumerate(metrics_data):
        for j, val in enumerate(row):
            c = tbl_met.cell(i, j)
            format_cell(c, val, bold=(i == 0 or j == 0), size=Pt(12))

    doc.add_paragraph().paragraph_format.space_after = Pt(6)

    # 4. TRL и план масштабирования
    add_gost_heading(doc, "4. Уровень технологической готовности (TRL 6–7) и план доработки", space_before=6, space_after=4)
    add_gost_paragraph(
        doc,
        "Текущее состояние разработки соответствует уровню TRL 6 (Технология валидирована в релевантных условиях):\n"
        "• Реализован полнофункциональный микросервисный стек: .NET Core 8 WebAPI, Next.js 14, gRPC, Apache Kafka, PyTorch;\n"
        "• Проверена сквозная работоспособность: захват сигналов Stalker Engine ➔ gRPC инференс нейросети ➔ "
        "синтез планов реструктуризации солвером ➔ мобильный экран ДБО ➔ мгновенное подтверждение по SMS.\n\n"
        "План масштабирования до TRL 8–9 (промышленное внедрение в БВУ РК):\n"
        "1. Q1–Q2 2027: Пилотное развертывание в регуляторной песочнице Нацбанка РК совместно с Bereke Bank и ГКБ;\n"
        "2. Q3 2027: Интеграция с национальными протоколами Open Banking / Open API Республики Казахстан;\n"
        "3. Q4 2027: Прохождение сертификации информационной безопасности в соответствии с Законом РК № 94-V «О персональных данных».",
        space_after=6
    )

    # 5. Репозиторий
    add_gost_heading(doc, "5. Сведения об открытом репозитории и исходном коде", space_before=6, space_after=4)
    add_gost_paragraph(
        doc,
        "Исходный программный код, веса обученных нейросетевых моделей, миграции базы данных и архитектурная документация "
        "размещены в репозитории проекта: github.com/suleimenov-risk/RiskTwin. Комплекс полностью автономен, разворачивается "
        "локально и готов к инспекции членами экспертного жюри конкурса.",
        space_after=0
    )

    doc.save(output_path)
    print(f"[OK] Generated: {output_path}")

if __name__ == "__main__":
    build_tech_appendix_document("test_tech.docx")
