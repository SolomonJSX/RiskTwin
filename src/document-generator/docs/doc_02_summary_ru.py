from docx import Document
from docx.shared import Pt
from styles import (
    apply_gost_page_setup, add_gost_paragraph, add_gost_heading
)

def build_summary_ru_document(output_path: str):
    doc = Document()
    apply_gost_page_setup(doc)

    # Заголовок документа (по ширине, отступ 0.75 см, Times New Roman 14 пт, жирный)
    add_gost_heading(doc, "РЕЗЮМЕ ПРОЕКТА (EXECUTIVE SUMMARY)", space_before=0, space_after=4)

    # Мета-данные проекта
    add_gost_paragraph(
        doc,
        "Тема исследования: RiskTwin: Цифровой двойник кредитного риска и превентивный оптимизатор реструктуризации.\n"
        "Автор проекта: Сулейменов Ж.С., студент-исследователь Карагандинского технического университета имени Абылкаса Сагинова (КарТУ).\n"
        "Тематический трек: AI for Finance (скоринг, прогнозирование рисков, LLM-сервисы, цифровая реструктуризация).",
        space_after=6
    )

    # 1. Проблема
    add_gost_heading(doc, "1. Актуальность и проблема в финансовом секторе Республики Казахстан", space_before=4, space_after=2)
    add_gost_paragraph(
        doc,
        "Рост розничной закредитованности в Республике Казахстан (более 8.5 млн активных заемщиков) "
        "существенно повышает риски формирования проблемной задолженности (NPL). Традиционные скоринговые "
        "системы банков реагируют ретроспективно: они фиксируют факт дефолта лишь при возникновении фактической "
        "просрочки платежа (30+ и 90+ DPD). На этом этапе коммерческий банк вынужден формировать максимальные "
        "провизии по МСФО 9 (Stage 3), а заемщик подвергается штрафным санкциям и коллекторскому взысканию, "
        "что приводит к разрушению платежеспособности и безвозвратным кредитным потерям.",
        space_after=4
    )

    # 2. Суть решения
    add_gost_heading(doc, "2. Суть разработанного решения: Платформа RiskTwin", space_before=4, space_after=2)
    add_gost_paragraph(
        doc,
        "RiskTwin представляет собой превентивную аналитическую платформу класса Early Warning System (EWS), "
        "формирующую динамический цифровой двойник финансово-поведенческого профиля заемщика. Сервис непрерывно "
        "считывает косвенные маркеры эмоционального и финансового стресса (ночные входы в ДБО с 03:00 до 05:00, "
        "сокращение базовых дискреционных трат, микрозаймы в МФО) и с помощью Dual-Tower нейросети с механизмом "
        "Cross-Attention прогнозирует кассовый разрыв за 30 дней до наступления дефолта. Встроенный оптимизационный "
        "солвер автоматически синтезирует персонализированные варианты реструктуризации и доставляет готовое "
        "предложение в мобильное банковское приложение заемщика без участия коллекторов.",
        space_after=4
    )

    # 3. Научная новизна
    add_gost_heading(doc, "3. Научно-техническая новизна и экспериментальные результаты", space_before=4, space_after=2)
    add_gost_paragraph(
        doc,
        "В проекте реализован Neuro-Symbolic AI подход: 1) Точность ранней классификации риска достигла "
        "AUC-ROC = 0.887 на выборке Home Credit Default Risk; 2) Ошибка оценки срока наступления разрыва (Cash Runway) "
        "составляет MAE = ±4.2 дня; 3) Реализована полная объяснимость решений (XAI) на базе алгоритма TreeSHAP, "
        "позволяющая риск-офицеру верифицировать первопричину стресса; 4) 3D-аватар Stress Twin обеспечивает наглядный "
        "мониторинг биоповеденческого стресса клиента.",
        space_after=4
    )

    # 4. Экономический эффект
    add_gost_heading(doc, "4. Практический эффект для банков и уровень готовности (TRL 6–7)", space_before=4, space_after=2)
    add_gost_paragraph(
        doc,
        "Превентивное урегулирование сохраняет кредиты в регуляторной категории Stage 2 по МСФО 9, предотвращая "
        "замораживание капитала в резервах и повышая итоговую возвратность задолженности на 35–40%. Проект разработан "
        "на базе микросервисной архитектуры (.NET Core 8 WebAPI, gRPC, Next.js, Apache Kafka, PyTorch) и полностью "
        "готов к интеграционному пилотированию в банках-партнерах конкурса (Bereke Bank, ГКБ, Halyk, Kaspi).",
        space_after=0
    )

    doc.save(output_path)
    print(f"[OK] Generated: {output_path}")

if __name__ == "__main__":
    build_summary_ru_document("test_summary_ru.docx")
